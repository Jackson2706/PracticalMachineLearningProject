def model_size_cell(summary, d: str, m: str) -> str:
    f = frozen(d, m)
    if family(m) == "neural":
        if not f:
            return MISSING
        from ksent.models.registry import nonemb_params, width_for

        emb, _ = summary_lookup(summary, d, m, ref_size(), "params_emb")
        return f"{count_fmt(nonemb_params(m, width_for(m, f['params']['width'])))} / {count_fmt(emb)}"
    n = ref_size()
    key = "n_nonzero_coef" if m in ("tfidf_lr", "tfidf_svm") else "total_nodes"
    mean, _ = summary_lookup(summary, d, m, n, key)
    return count_fmt(mean)


