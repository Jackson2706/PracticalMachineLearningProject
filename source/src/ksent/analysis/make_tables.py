def val_marks(bs: pd.DataFrame | None, d: str) -> dict[int, tuple[str, str]]:
    if bs is None:
        return {}
    sub = bs[(bs.dataset == d) & (bs.selection == "val")]
    return {int(r["size"]): (r.best_tfidf, r.best_neural) for _, r in sub.iterrows()}


def size_table(name: str, summary, metric: str, bs=None) -> None:
    ncol = len(size_columns())
    body = [f"Method & {size_header()} \\\\", r"\midrule"]
    for di, d in enumerate(datasets()):
        full = f"{sizes(d)[-1]:,}".replace(",", "{,}")
        body.append(rf"\multicolumn{{{ncol + 1}}}{{l}}{{\textit{{{dname(d)}}} (full = {full})}} \\")
        body += method_rows_block(summary, d, aligned_sizes(d), metric, marks=val_marks(bs, d) if bs is not None else None)
        if di < len(datasets()) - 1:
            body.append(r"\midrule")
    write(name, wrap("\n".join(body), "l" + "r" * ncol))


