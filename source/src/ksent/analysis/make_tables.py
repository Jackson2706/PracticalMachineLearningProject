    body = [head1, cm, head2, r"\midrule"]
    for di, d in enumerate(datasets()):
        sub = cells[cells.dataset == d] if cells is not None else None
        ms = list(dict.fromkeys(sub.method)) if sub is not None and len(sub) else ["best TF-IDF", "best neural"]
        for mi, m in enumerate(ms):
            out = []
            for n in ns:
                vals = []
                for t in toks:
                    r = sub[(sub.method == m) & (sub.tokenizer == t) & (sub["size"] == n)] if sub is not None and len(sub) else None
                    vals.append((r.test_macro_f1_mean.iloc[0], r.test_macro_f1_std.iloc[0], r.val_macro_f1_mean.iloc[0])
                                if r is not None and len(r) else (np.nan, np.nan, np.nan))
                b_test = best_idx([v[0] for v in vals])
                b_val = best_idx([v[2] for v in vals])
                for j, (mean, std, _) in enumerate(vals):
                    cell = pm(mean, std, 100, 2, bold=b_test == j)
                    out.append(cell + (r"$^{\star}$" if b_val == j and cell != MISSING else ""))
            lead = rf"\multirow{{{len(ms) + 1}}}{{*}}{{{dname(d)}}}" if mi == 0 else ""
            body.append(f"{lead} & {mname(m) if m in ABBR else m} & " + " & ".join(out) + r" \\")
        gap_cells = []
        for n in ns:
            r = gaps[(gaps.dataset == d) & (gaps["size"] == n)] if gaps is not None and len(gaps) else None
            if r is not None and len(r) and isnum(r.gap_best_mean.iloc[0]):
                r = r.iloc[0]
                txt = (f"{pm(r.gap_best_mean, r.gap_best_std, 1, 2)} "
                       f"({TOK_NAME.get(r.best_tokenizer_neural)} vs {TOK_NAME.get(r.best_tokenizer_tfidf)}; "
                       f"Kiwi: {pm(r.gap_main_mean, None, 1, 2)})")
            else:
                txt = MISSING
            gap_cells.append(rf"\multicolumn{{{len(toks)}}}{{c}}{{{txt}}}")
        body.append(r" & \textit{Gap, best tok.} & " + " & ".join(gap_cells) + r" \\")
        if di < len(datasets()) - 1:
            body.append(r"\midrule")
    write("table6", wrap("\n".join(body), "ll" + "r" * len(toks) * len(ns)))


