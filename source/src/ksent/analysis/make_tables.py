# ------------------------------------------------------------------ helpers
def wrap(body: str, colspec: str) -> str:
    return (HEADER + "\\begin{adjustbox}{max width=\\linewidth}\n\\begin{tabular}{" + colspec + "}\n\\toprule\n"
            + body.rstrip() + "\n\\bottomrule\n\\end{tabular}\n\\end{adjustbox}\n")


def write(name: str, text: str) -> None:
    TABLE_DIR.mkdir(parents=True, exist_ok=True)
    (TABLE_DIR / f"{name}.tex").write_text(text, encoding="utf-8")
    print(f"  wrote tables/{name}.tex  ({count_missing(text)} placeholders)")


def best_idx(values: list[float], higher: bool = True) -> int | None:
    arr = np.array([v if isnum(v) else np.nan for v in values], dtype=float)
    if np.all(np.isnan(arr)):
        return None
    return int(np.nanargmax(arr) if higher else np.nanargmin(arr))


def frozen(d: str, m: str) -> dict | None:
    p = frozen_path(d, m)
    return load_yaml(p) if p.exists() else None


def short_cfg(m: str, p: dict | None) -> str:
    """Compact description of a selected configuration."""
    if not p:
        return MISSING
    if m in ("tfidf_lr", "tfidf_svm"):
        return f"$C$={p['C']:g}"
    if m == "tfidf_rf":
        depth = "$\\infty$" if p.get("max_depth") is None else p["max_depth"]
        cw = "bal" if p.get("class_weight") else "none"
        return f"{p['n_estimators']}T, d{depth}, {p['max_features']}, l{p['min_samples_leaf']}, {cw}"
    if m == "tfidf_xgb":
        return f"d{p['max_depth']}, $\\eta$={p['learning_rate']:g}, s{p['subsample']:g}, R={p.get('n_estimators', MISSING)}"
    return f"{p['width']}, lr={float(p['lr']):.0e}, p={p['dropout']:g}".replace("e-0", "e-")


def method_rows_block(summary, d: str, size_or_sizes, metric: str, scale: float = 100, dec: int | None = 2,
                      higher: bool = True, marks: dict[int, tuple[str, str]] | None = None) -> list[str]:
    """Rows for one dataset block: one row per method, one column per size (``None`` = blank column)."""
    cols = size_or_sizes
    cells = {m: [summary_lookup(summary, d, m, n, metric) if n is not None else (None, None) for n in cols]
             for m in methods()}
    best = [best_idx([cells[m][j][0] for m in methods()], higher) if n is not None else None
            for j, n in enumerate(cols)]
    rows = []
    for i, m in enumerate(methods()):
        out = []
        for j, n in enumerate(cols):
            if n is None:
                out.append("")
                continue
            mean, std = cells[m][j]
            s = pm(mean, std, scale, dec, bold=(best[j] == i))
            if marks and n in marks and s != MISSING:
                if marks[n][0] == m:
                    s += r"$^{\dagger}$"
                if marks[n][1] == m:
                    s += r"$^{\ddagger}$"
            out.append(s)
        rows.append(f"{mname(m)} & " + " & ".join(out) + r" \\")
        if m == TFIDF_METHODS[-1]:
            rows.append(r"\cmidrule(lr){1-%d}" % (len(cols) + 1))
    return rows


def size_header() -> str:
    return " & ".join(("$n$=" + c if c[0].isdigit() else c).replace(",", "{,}") for c in size_columns())


