def table_arch() -> None:
    from ksent.models.registry import model_widths, nonemb_params

    widths, targets = model_widths(), global_cfg()["neural"]["width_targets"]
    lv = list(targets)
    head = ("Method & Backbone & Fixed structure & Width = & "
            + " & ".join(rf"{l} ({count_fmt(t)})" for l, t in targets.items()) + r" \\")
    body = [head, r"\midrule"]
    for m in NEURAL_METHODS:
        if m not in widths:
            continue
        bb, wmean, fixed = ARCH[m]
        cells = [f"{widths[m][l]} ({count_fmt(nonemb_params(m, widths[m][l]))})" for l in lv]
        body.append(f"{mname(m)} & {bb} & {fixed} & {wmean} & " + " & ".join(cells) + r" \\")
    write("table_arch", wrap("\n".join(body), r"l>{\raggedright\arraybackslash}p{5.2cm}>{\raggedright\arraybackslash}p{2.8cm}l" + "r" * len(lv)))


