"""Write ``submission/report/generated/numbers.tex``: one macro per number cited in text.

The report and slides cite results *only* through these macros. A macro whose
source value does not exist yet expands to ``\\TBD{name}`` (rendered red), so the
documents always compile and nothing is ever invented.

Dataset suffixes: NSMC, Shopping, Steam (e.g. ``\\crossoverNSMC``, ``\\gapSteam``).
Usage: ``python -m ksent.analysis.make_numbers [--list]``
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd

from ksent.analysis.common import (AGG_DIR, GEN_DIR, datasets, dname, isnum, mname, read_csv, sizes, summary_lookup,
                                   tex_escape)
from ksent.config import NEURAL_METHODS, TFIDF_METHODS, global_cfg, path
from ksent.utils import read_json

SUFFIX = {"nsmc": "NSMC", "shopping": "Shopping", "steam": "Steam"}


def _n(x: float) -> str:
    """Thousands separator safe for LaTeX."""
    return f"{int(x):,}".replace(",", "{,}")


def _pm(mean, std, scale: float = 1.0, dec: int = 2) -> str | None:
    if not isnum(mean):
        return None
    s = f"{float(mean) * scale:.{dec}f}"
    if isnum(std):
        s += rf" \pm {float(std) * scale:.{dec}f}"
    return rf"\ensuremath{{{s}}}"


def _f(x, dec: int = 2, suffix: str = "") -> str | None:
    return f"{float(x):.{dec}f}{suffix}" if isnum(x) else None


class Numbers:
    """Ordered collection of macro definitions (value ``None`` -> TBD)."""

    def __init__(self) -> None:
        self.items: list[tuple[str, str | None, str]] = []

    def add(self, name: str, value: str | None, doc: str) -> None:
        assert name.isalpha(), f"macro names must be letters only: {name}"
        self.items.append((name, value, doc))

    def render(self) -> str:
        lines = ["% AUTO-GENERATED by ksent.analysis.make_numbers (do not edit by hand).",
                 "% Every number cited in the report/slides comes from these macros.", ""]
        for name, value, doc in self.items:
            body = value if value is not None else rf"\TBD{{{name}}}"
            lines.append(rf"\newcommand{{\{name}}}{{{body}}}  % {doc}")
        return "\n".join(lines) + "\n"


def build() -> Numbers:
    g = global_cfg()
    N = Numbers()
    summary, ct, runs = read_csv("summary.csv"), read_csv("crossover.csv"), read_csv("runs.csv")
    mg, frozen = read_csv("marginal_gains.csv"), read_csv("frozen.csv")
    stats_p = AGG_DIR / "dataset_stats.json"
    stats = read_json(stats_p) if stats_p.exists() else {"datasets": {}}
    hw_p = path("results") / "env" / "hardware.json"
    hw = read_json(hw_p) if hw_p.exists() else {}
    nmax = max(sizes())

    # ---- design constants (from configs)
    N.add("nSeeds", str(len(g["seeds"])), "experiment seeds")
    N.add("seedList", ", ".join(str(s) for s in g["seeds"]), "seed values")
    n_final = len(g["datasets"]) * len(g["methods"]) * len(g["sizes"]) * len(g["seeds"])
    N.add("nFinalFits", _n(n_final), "planned final fits")
    N.add("nTuningFits", _n(len(g["datasets"]) * len(g["methods"]) * 10), "planned tuning fits")
    N.add("nThreads", str(g["n_threads"]), "CPU threads")
    sc = g.get("scheduler") or {}
    N.add("neuralThreads", str(g.get("neural_threads") or g["n_threads"]), "CPU threads per neural training job")
    N.add("kGpu", str(sc["k_gpu"]) if sc.get("k_gpu") else None, "concurrent neural jobs per GPU (quality runs)")
    N.add("cpuJobs", str(sc["cpu_jobs"]) if sc.get("cpu_jobs") else None, "concurrent classical jobs (quality runs)")
    N.add("crossoverMargin", f"{float(g['analysis']['crossover_margin']):.1f}", "crossover margin (macro-F1 points)")
    N.add("dataSeed", str(g["data_seed"]), "split seed")

    # ---- environment / bookkeeping (from results)
    meta_p = AGG_DIR / "meta.json"
    meta = read_json(meta_p) if meta_p.exists() else {}

    def joined(key: str) -> str | None:
        v = meta.get(key)
        return tex_escape(", ".join(map(str, v))) if v else None

    N.add("cpuModel", tex_escape(hw["cpu_model"]) if hw.get("cpu_model") else None, "CPU model")
    N.add("gpuModel", tex_escape(hw["gpu_name"]) if hw.get("gpu_name") else None, "GPU / accelerator model")
    N.add("trainDevice", joined("train_devices"), "neural training device(s) of the reported runs")
    N.add("accelDevice", joined("accelerator_devices"), "accelerator used for neural latency")
    N.add("precisionUsed", joined("precisions"), "numeric precision of reported runs")
    N.add("mambaBackend", joined("mamba_backends"), "Mamba backend of reported runs")
    N.add("hardwareNote", (r"\textcolor{red}{results mix several machines}" if meta.get("mixed_hardware") else
                           "all results from one machine") if meta else None, "hardware consistency")
    N.add("nRunsDone", _n(meta["n_main_runs"]) if meta.get("n_main_runs") else None, "successful main runs")
    N.add("nAblationRunsDone", _n(meta["n_ablation_runs"]) if meta.get("n_ablation_runs") else None,
          "successful ablation-only runs")
    ab = g["ablation"]
    n_ab = len(g["datasets"]) * 2 * len([t for t in ab["tokenizers"] if t != g["tokenizer"]]) * len(ab["sizes"]) \
        * len(g["seeds"])
    N.add("nAblationFits", _n(n_ab), "planned new ablation fits")
    msl = g.get("max_seq_len") or {}
    for tok, nm in (("kiwi", "Kiwi"), ("whitespace", "Whitespace"), ("char", "Char")):
        N.add(f"maxSeqLen{nm}", str(msl[tok]) if msl.get(tok) else None, f"max sequence length ({tok})")
    N.add("totalTuningHours", _f(frozen.tuning_time_total_s.sum() / 3600, 2) if frozen is not None else None,
          "total tuning fit time (h)")
    N.add("totalSweepHours", _f(runs.wall_s.sum() / 3600, 1) if runs is not None else None,
          "total wall time of final runs (h)")

    # ---- per dataset
    for d in datasets():
        X = SUFFIX.get(d, d.capitalize())
        c = (stats["datasets"].get(d) or {}).get("cleaning") or {}
        N.add(f"nRaw{X}", _n(c["raw"]) if c else None, f"{dname(d)} raw reviews")
        N.add(f"nClean{X}", _n(c["clean"]) if c else None, f"{dname(d)} reviews after cleaning")
        N.add(f"nKiwiEmpty{X}", _n(c["kiwi_empty"]) if c else None, f"{dname(d)} reviews dropped for zero Kiwi tokens")
        N.add(f"nRatingThree{X}", _n(c["neutral_dropped"]) if c else None, f"{dname(d)} rating-3 reviews dropped")
        sym = (stats["datasets"].get(d) or {}).get("symbols")
        N.add(f"symbolShare{X}", _f(sym["pct_any_symbol"], 1, r"\%") if sym else None,
              f"{dname(d)} reviews containing kk/yu/h jamo or emoji")
        sp = ((stats["datasets"].get(d) or {}).get("splits") or {}).get("train_pool") or {}
        N.add(f"truncKiwi{X}", _f(sp.get("trunc_pct"), 1, r"\%") if sp.get("trunc_pct") is not None else None,
              f"{dname(d)} train-pool reviews truncated (Kiwi)")
        oov_df = read_csv("diagnostics_oov.csv")
        for n_, nm in ((min(sizes()), "Small"), (max(sizes()), "Large")):
            o = None if oov_df is None else oov_df[(oov_df.dataset == d) & (oov_df.tokenizer == "kiwi")
                                                   & (oov_df["size"] == n_)]
            N.add(f"oov{nm}{X}", _f(o.oov_token_rate.mean() * 100, 1, r"\%") if o is not None and len(o) else None,
                  f"{dname(d)} test OOV token rate (Kiwi vocab) at n={n_}")

        # tokenizer ablation
        gaps = read_csv("ablation_gap.csv")
        gsub = gaps[gaps.dataset == d] if gaps is not None else None
        has_ab = gsub is not None and len(gsub) > 0
        N.add(f"ablationTfidf{X}", mname(gsub.tfidf_method.iloc[0]) if has_ab else None, "ablation TF-IDF method")
        N.add(f"ablationNeural{X}", mname(gsub.neural_method.iloc[0]) if has_ab else None, "ablation neural method")
        tok_name = {"whitespace": "eojeol", "kiwi": "Kiwi", "char": "character"}
        for n_, nm in ((min(g["ablation"]["sizes"]), "Small"), (max(g["ablation"]["sizes"]), "Large")):
            r = gsub[gsub["size"] == n_] if has_ab else None
            ok = r is not None and len(r) and isnum(r.get("gap_best_mean", pd.Series([np.nan])).iloc[0])
            N.add(f"ablationGap{nm}{X}", _pm(r.gap_best_mean.iloc[0], r.gap_best_std.iloc[0]) if ok else None,
                  f"gap with each family's best tokenizer at n={n_}")
            if nm == "Large":
                N.add(f"bestTokenizerTfidf{X}", tok_name.get(r.best_tokenizer_tfidf.iloc[0]) if ok else None,
                      f"best TF-IDF tokenizer (validation) at n={n_}")
                N.add(f"bestTokenizerNeural{X}", tok_name.get(r.best_tokenizer_neural.iloc[0]) if ok else None,
                      f"best neural tokenizer (validation) at n={n_}")
        holds = None
        if has_ab and "conclusion_holds" in gsub and gsub.conclusion_holds.notna().all():
            holds = "yes" if gsub.conclusion_holds.astype(bool).all() else "no"
        N.add(f"ablationHolds{X}", holds, "does the main conclusion hold with the best tokenizers")

        row = {}
        if ct is not None:
            sub = ct[(ct.dataset == d) & (ct.selection == "val")]
            row = sub.iloc[0].to_dict() if len(sub) else {}
        has = bool(row) and isinstance(row.get("best_tfidf"), str)
        thr = None
        if has:
            thr = _n(row["threshold"]) if isnum(row.get("threshold")) else r"none up to 8{,}000"
        N.add(f"crossover{X}", thr, f"{dname(d)} crossover threshold (val-selected winners)")
        tsel = None
        if ct is not None:
            sub = ct[(ct.dataset == d) & (ct.selection == "test")]
            if len(sub):
                tsel = _n(sub.threshold.iloc[0]) if isnum(sub.threshold.iloc[0]) else r"none up to 8{,}000"
        N.add(f"crossoverTestSel{X}", tsel, f"{dname(d)} threshold with test-selected winners (sensitivity)")
        N.add(f"evalSize{X}", _n(row["eval_size"]) if has else None, "size used for the Pareto check")
        N.add(f"bestTfidf{X}", mname(row["best_tfidf"]) if has else None, "best TF-IDF method at eval size")
        N.add(f"bestNeural{X}", mname(row["best_neural"]) if has else None, "best neural method at eval size")
        N.add(f"gap{X}", _pm(row.get("gap_mean"), row.get("gap_std")) if has else None,
              "neural - TF-IDF test macro-F1 gap at eval size (points)")
        pe = row.get("neural_pareto_efficient") if has else None
        N.add(f"pareto{X}", None if pe is None or (isinstance(pe, float) and np.isnan(pe)) else ("yes" if bool(pe) else "no"),
              "is the neural winner Pareto-efficient vs the TF-IDF winner")
        for key, nm in (("latency_ratio", "latencyRatio"), ("fit_ratio", "fitRatio"), ("ram_ratio", "ramRatio")):
            N.add(f"{nm}{X}", _f(row.get(key), 1, r"\ensuremath{\times}") if has else None,
                  f"neural / TF-IDF {key.replace('_', ' ')}")
        N.add(f"tfidfLatency{X}", _f(row.get("tfidf_lat_cpu_e2e_ms"), 3) if has else None, "TF-IDF winner CPU e2e ms")
        N.add(f"neuralLatency{X}", _f(row.get("neural_lat_cpu_e2e_ms"), 3) if has else None, "neural winner CPU e2e ms")

        # largest size: overall best, family bests, gap
        best_m, best_v = None, (np.nan, np.nan)
        fam_best: dict[str, tuple[str | None, tuple]] = {}
        if summary is not None:
            cell = summary[(summary.dataset == d) & (summary["size"] == nmax)].dropna(subset=["test_macro_f1_mean"])
            if len(cell):
                b = cell.sort_values("test_macro_f1_mean", ascending=False).iloc[0]
                best_m, best_v = b.method, (b.test_macro_f1_mean, b.test_macro_f1_std)
            for fam, ms in (("tfidf", TFIDF_METHODS), ("neural", NEURAL_METHODS)):
                fc = cell[cell.method.isin(ms)].dropna(subset=["val_macro_f1_mean"]) if len(cell) else cell
                if len(fc):
                    fb = fc.sort_values("val_macro_f1_mean", ascending=False).iloc[0]
                    fam_best[fam] = (fb.method, (fb.test_macro_f1_mean, fb.test_macro_f1_std))
        N.add(f"bestMethod{X}", mname(best_m) if best_m else None, f"best method by test macro-F1 at n={nmax}")
        N.add(f"macroFOneBest{X}", _pm(*best_v, 100) if best_m else None, f"its test macro-F1 (x100) at n={nmax}")
        for fam, nm in (("tfidf", "Tfidf"), ("neural", "Neural")):
            m_, v_ = fam_best.get(fam, (None, (np.nan, np.nan)))
            N.add(f"bestEightK{nm}{X}", mname(m_) if m_ else None, f"val-selected best {fam} at n={nmax}")
            N.add(f"macroFOneEightK{nm}{X}", _pm(*v_, 100) if m_ else None, f"its test macro-F1 (x100) at n={nmax}")
        mam = summary_lookup(summary, d, "small_mamba", nmax, "test_macro_f1")
        N.add(f"mambaFOne{X}", _pm(*mam, 100), f"Mamba test macro-F1 at n={nmax}")

        # marginal gains of the overall best method
        for a, b, nm in ((sizes()[0], sizes()[1], "gainFirst"), (sizes()[-2], sizes()[-1], "gainLast")):
            val = None
            if mg is not None and best_m:
                r = mg[(mg.dataset == d) & (mg.method == best_m) & (mg.from_size == a)]
                if len(r):
                    val = _pm(r.gain_mean.iloc[0], r.gain_std.iloc[0])
            N.add(f"{nm}{X}", val, f"best method's macro-F1 gain {a}->{b} (points)")
    # compute used per stage (ksent.analysis.compute_usage) and cost-vs-quality determinism
    cu = read_csv(AGG_DIR / "compute_usage.csv")
    stage_macro = {"C pilot": "Pilot", "D tuning": "Tuning", "E main sweep": "Sweep", "F ablation": "Ablation",
                   "G cost pass": "CostPass"}
    for st, nm in stage_macro.items():
        r = cu[cu.stage == st] if cu is not None else None
        ok = r is not None and len(r) > 0
        N.add(f"wall{nm}", _f(r.busy_wall_h.iloc[0], 2) if ok else None, f"{st}: busy wall time (h)")
        N.add(f"gpuUtil{nm}", _f(r.avg_gpu_util_pct.iloc[0], 0, r"\%") if ok else None, f"{st}: mean GPU util")
        N.add(f"cpuUtil{nm}", _f(r.avg_cpu_util_pct.iloc[0], 1, r"\%") if ok else None,
              f"{st}: mean CPU util (all logical cores)")
    N.add("wallTotal", _f(cu.busy_wall_h.sum(), 1) if cu is not None else None, "total busy wall time (h)")
    N.add("gpuJobHours", _f(cu.gpu_job_h.sum(), 1) if cu is not None else None,
          "summed duration of all GPU (neural) jobs (h)")
    # crossover winners at the evaluation size: class-specific error rates, accelerator latency, last gain
    xo = read_csv(AGG_DIR / "crossover.csv")
    conf = read_csv(AGG_DIR / "confusion_n8000.csv")
    summ = read_csv(AGG_DIR / "summary.csv")
    mgain = read_csv(AGG_DIR / "marginal_gains.csv")
    for d in datasets():
        X = SUFFIX[d]
        r = xo[(xo.dataset == d) & (xo.selection == "val")] if xo is not None else None
        win = {"Tfidf": r.best_tfidf.iloc[0], "Neural": r.best_neural.iloc[0]} if r is not None and len(r) else {}
        for fam in ("Tfidf", "Neural"):
            c = conf[(conf.dataset == d) & (conf.method == win[fam])] if conf is not None and fam in win else None
            ok = c is not None and len(c) > 0 and {"fpr", "fnr"} <= set(c.columns)
            N.add(f"fpr{fam}{X}", _f(c.fpr.iloc[0] * 100, 1, r"\%") if ok else None,
                  f"{fam} winner: negatives predicted positive (n=8000, pooled over seeds)")
            N.add(f"fnr{fam}{X}", _f(c.fnr.iloc[0] * 100, 1, r"\%") if ok else None,
                  f"{fam} winner: positives predicted negative (n=8000, pooled over seeds)")
        s = summ[(summ.dataset == d) & (summ["size"] == 8000) & (summ.method == win.get("Neural"))] \
            if summ is not None else None
        ok = s is not None and len(s) > 0 and "lat_acc_e2e_ms_mean" in s
        N.add(f"neuralAccLatency{X}", _f(s.lat_acc_e2e_ms_mean.iloc[0], 3) if ok else None,
              "neural winner accelerator e2e latency (ms, batch 1)")
        g = mgain[(mgain.dataset == d) & (mgain.method == win.get("Neural")) & (mgain.from_size == 4000)] \
            if mgain is not None else None
        N.add(f"gainLastNeural{X}", _pm(g.gain_mean.iloc[0], g.gain_std.iloc[0]) if g is not None and len(g) else None,
              "neural winner's macro-F1 gain 4000->8000 (points)")
    det = read_csv(AGG_DIR / "determinism_by_method.csv")
    N.add("detRuns", _n(det.runs.sum()) if det is not None else None, "cost runs compared with quality runs")
    N.add("detIdentical", _n(det.identical_runs.sum()) if det is not None else None,
          "cost runs with predictions identical to quality mode")
    N.add("detMaxDisagree", _f(det.max_disagree_pct.max(), 1, r"\%") if det is not None else None,
          "max per-run disagreement of test predictions")
    return N


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--list", action="store_true", help="print macro names and whether they are filled")
    args = ap.parse_args()
    nums = build()
    GEN_DIR.mkdir(parents=True, exist_ok=True)
    (GEN_DIR / "numbers.tex").write_text(nums.render(), encoding="utf-8")
    n_tbd = sum(v is None for _, v, _ in nums.items)
    print(f"  wrote generated/numbers.tex  ({len(nums.items)} macros, {n_tbd} TBD)")
    if args.list:
        for name, v, doc in nums.items:
            print(f"   \\{name:28s} {'TBD' if v is None else v:30s} {doc}")


if __name__ == "__main__":
    main()
