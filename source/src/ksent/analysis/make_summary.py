"""Write ``submission/RESULTS_SUMMARY.md``: a one-page summary whose numbers all come from the
same generated macros as the report (``ksent.analysis.make_numbers``) plus result counts.

Usage: ``python -m ksent.analysis.make_summary``
"""
from __future__ import annotations

import json
import re

from ksent.analysis.common import AGG_DIR, read_csv
from ksent.analysis.make_numbers import build
from ksent.config import SOURCE_DIR, path

OUT = SOURCE_DIR.parent / "submission" / "RESULTS_SUMMARY.md"


def plain(v: str | None) -> str:
    """LaTeX macro value -> Markdown text."""
    if v is None:
        return "n/a"
    v = re.sub(r"\\ensuremath\{(.*)\}", r"\1", v)
    for a, b in ((r"\pm", "±"), (r"\times", "×"), (r"\%", "%"), ("{,}", ","), (r"\_", "_"), ("$", "")):
        v = v.replace(a, b)
    return re.sub(r"\s+", " ", v.replace("{", "").replace("}", "")).strip()


def main() -> None:
    m = {name: plain(v) for name, v, _ in build().items}
    counts = {k: sum(1 for p in (path("results") / sub).rglob("*.json") if not p.name.endswith(".failed.json"))
              for k, sub in (("tuning", "tuning"), ("quality", "raw"), ("cost", "cost/raw"))}
    fp = path("results") / "failed.jsonl"
    n_failed = len([ln for ln in fp.read_text().splitlines() if ln.strip()]) if fp.exists() else 0
    meta = json.loads((AGG_DIR / "meta.json").read_text()) if (AGG_DIR / "meta.json").exists() else {}
    cu = read_csv(AGG_DIR / "compute_usage.csv")
    stage_rows = "\n".join(
        f"| {r.stage} | {r.run_mode} | {r.runs} | {r.busy_wall_h:.2f} | {r.avg_gpu_util_pct:.0f}% | {r.avg_cpu_util_pct:.1f}% |"
        for r in cu.itertuples() if r.runs) if cu is not None else ""
    ds = (("NSMC", "NSMC (movies)"), ("Shopping", "Shopping"), ("Steam", "Steam (games)"))
    answer = "\n".join(
        f"| {lab} | {m['crossover' + x]} | {m['bestTfidf' + x]} vs {m['bestNeural' + x]} | {m['ablationGapSmall' + x]} "
        f"| {m['gap' + x]} | {m['fitRatio' + x]} | {m['latencyRatio' + x]} | {m['ramRatio' + x]} | {m['pareto' + x]} |"
        for x, lab in ds)
    best = "; ".join(f"{x} {m['bestMethod' + x]} {m['macroFOneBest' + x]}" for x, _ in ds)
    neural = "; ".join(f"{x} {m['bestEightKNeural' + x]} {m['macroFOneEightKNeural' + x]}" for x, _ in ds)
    mamba = " / ".join(m["mambaFOne" + x] for x, _ in ds)
    abl = "; ".join(f"{x}: {m['ablationGapLarge' + x]} (best tokenizers TF-IDF {m['bestTokenizerTfidf' + x]}, "
                    f"neural {m['bestTokenizerNeural' + x]}; holds: {m['ablationHolds' + x]})" for x, _ in ds)
    text = f"""# Results summary — Korean sentiment: neural vs TF-IDF crossover

*Generated by `python -m ksent.analysis.make_summary` from `source/results/` (same macros as the report).*

## Answer to the research question

**No crossover up to 8,000 reviews on any dataset.** The best neural model never beats the best TF-IDF
model by ≥ {m['crossoverMargin']} macro-F1 point at any size (winners selected on validation; the test-selected
sensitivity check agrees: {m['crossoverTestSelNSMC']} / {m['crossoverTestSelShopping']} / {m['crossoverTestSelSteam']}).

| Dataset | Threshold | Winners at 8k (TF-IDF vs neural) | Gap @500 (pts) | Gap @8k (pts) | Fit time ratio | CPU latency ratio | RAM ratio | Neural Pareto-efficient |
|---|---|---|---|---|---|---|---|---|
{answer}

Gap = neural − TF-IDF, paired per seed, mean ± sample std over {m['nSeeds']} seeds. Ratios = neural / TF-IDF winner at
n = 8,000 (exclusive cost runs). Steam's neural winner is Pareto-efficient only via slightly lower CPU latency
({m['neuralLatencySteam']} vs {m['tfidfLatencySteam']} ms); it is less accurate, slower to fit and uses more RAM.

## Key numbers (test macro-F1 ×100, n = 8,000)

- Best overall: {best}.
- Best neural (val-selected): {neural}.
- Mamba (weakest neural, `{m['mambaBackend']}` backend): {mamba}.
- Gap closes with data but no method saturates: last doubling (4k→8k) adds {m['gainLastNSMC']} / {m['gainLastShopping']} /
  {m['gainLastSteam']} points for the TF-IDF winner and {m['gainLastNeuralNSMC']} / {m['gainLastNeuralShopping']} /
  {m['gainLastNeuralSteam']} for the neural winner (NSMC / Shopping / Steam).
- Test OOV rate of the neural vocabulary: {m['oovSmallNSMC']} / {m['oovSmallShopping']} / {m['oovSmallSteam']} at n = 500 →
  {m['oovLargeNSMC']} / {m['oovLargeShopping']} / {m['oovLargeSteam']} at n = 8,000 (plausible cause of the weak neural start).
- Deterministic models (TF-IDF + LR/SVM) have std = 0 at n = 8,000 (every seed uses the full pool).
  Five seeds measure variability; they are not a significance test.

## Tokenizer ablation verdict

The conclusion holds under each family's best (validation-selected) tokenizer. Gap at n = 8,000: {abl}.
Kiwi morphemes are best for both families almost everywhere; eojeol is clearly worst. On Shopping at 8k validation
picks character TF-IDF, which is worse on test, so the gap turns positive but stays below {m['crossoverMargin']} point.

## Compute used

One machine: {m['gpuModel']} (1 GPU), {m['cpuModel']}, {m['precisionUsed']}, {m['nThreads']} threads per TF-IDF job,
{m['neuralThreads']} per neural job; quality stages ran {m['kGpu']} GPU jobs + {m['cpuJobs']} CPU jobs concurrently,
cost stages one job at a time.

| Stage | Mode | Runs | Busy wall (h) | Mean GPU util | Mean CPU util (of 128 logical) |
|---|---|---|---|---|---|
{stage_rows}

Total busy wall time {m['wallTotal']} h = {m['wallTotal']} GPU-hours on one GPU ({m['gpuJobHours']} h of summed
neural-job time). Busy wall excludes waiting for exclusivity (the pilot first waited for unrelated GPU jobs to finish).

## Result counts, failures and anomalies

- Tuning fits {counts['tuning']} / 270, quality fits {counts['quality']} (main {meta.get('n_main_runs', 'n/a')} / 675 +
  ablation {meta.get('n_ablation_runs', 'n/a')} / 120), cost fits {counts['cost']} / 135; crossover-size cost fits: 0
  (no crossover). Every dataset × method × size has 5 valid seeds.
- **Failures: {n_failed}** (`source/results/failed.jsonl` is empty); no retries were needed.
- Determinism: {m['detIdentical']} / {m['detRuns']} cost runs reproduce their quality-mode test predictions exactly
  (max disagreement {m['detMaxDisagree']}), for classical and GPU-trained models alike.
- Container restart at 05:44 UTC interrupted tuning at 100/270; resumed without redoing finished fits.
- Scheduler bottleneck in the first 19 min of the main sweep (one job at a time); fixed (scheduling only, predictions
  unaffected), 4 in-flight fits discarded and rerun.
- High seed variance at n = 500 for Steam LSTM / Transformer (one or two poorly trained seeds); reported, not removed.
- Deviations: Python 3.12 instead of 3.11 (pinned numpy 2.5.4 needs ≥ 3.12); Mamba uses the `torch_ref` backend (no
  mamba-ssm wheel for torch 2.14); 5 seeds instead of 3; tokenizer ablation added; costs measured at n = 8,000 only.

## Deliverables

- Report: `submission/report/main.pdf`
- Slides: `submission/slides/slides.pdf`
- Run journal: `source/logs/RUN_JOURNAL.md`; reproduce everything: `bash source/scripts/run_everything.sh`
"""
    OUT.write_text(text, encoding="utf-8")
    print(f"  wrote {OUT.relative_to(SOURCE_DIR.parent)}")


if __name__ == "__main__":
    main()
