"""Method registry, neural model construction and parameter-budget matching.

Width levels S/M/L map to an architecture-specific width (hidden size or
d_model) chosen so that *non-embedding* parameter counts match the targets in
``global.yaml: neural.width_targets`` (±15%). The resolved widths live in
``configs/model_widths.yaml`` and are (re)generated by ``scripts/count_params.py --write``.
"""
from __future__ import annotations

from typing import Any

from torch import nn

from ksent.config import NEURAL_METHODS, TFIDF_METHODS, dump_yaml, global_cfg, load_yaml, path, search_space
from ksent.models.mamba import SmallMamba
from ksent.models.mlp import EmbMLP
from ksent.models.rnn import EmbRNN
from ksent.models.transformer import SmallTransformer

# width search grids per architecture (transformer: multiples of nhead)
_WIDTH_GRID: dict[str, range] = {
    "emb_mlp": range(8, 2049),
    "emb_lstm": range(4, 1025),
    "emb_gru": range(4, 1025),
    "small_transformer": range(8, 513, 4),
    "small_mamba": range(8, 513, 2),
}
EMBEDDING_PARAM_PREFIXES: tuple[str, ...] = ("embedding.", "pos_embedding.")


def is_neural(method: str) -> bool:
    return method in NEURAL_METHODS


def is_tfidf(method: str) -> bool:
    return method in TFIDF_METHODS


def build_neural(method: str, vocab_size: int, width: int, dropout: float, max_len: int,
                 fixed: dict[str, Any] | None = None, mamba_backend: str = "torch_ref") -> nn.Module:
    """Instantiate a neural classifier (on CPU; move it with ``hardware.to_device``)."""
    kw = dict(fixed or {})
    kw.pop("config_id", None)
    kw.pop("backend", None)
    emb = int(global_cfg()["neural"]["embed_dim"])
    common = dict(vocab_size=vocab_size, embed_dim=emb, width=int(width), dropout=float(dropout), max_len=max_len)
    if method == "emb_mlp":
        return EmbMLP(**common, **kw)
    if method == "emb_lstm":
        return EmbRNN(**common, cell="lstm", **kw)
    if method == "emb_gru":
        return EmbRNN(**common, cell="gru", **kw)
    if method == "small_transformer":
        return SmallTransformer(**common, **kw)
    if method == "small_mamba":
        return SmallMamba(**common, backend=mamba_backend, **kw)
    raise KeyError(method)


def count_params(model: nn.Module) -> dict[str, int]:
    """Embedding (token + positional tables) vs non-embedding parameter counts."""
    emb = non = 0
    for name, p in model.named_parameters():
        if name.startswith(EMBEDDING_PARAM_PREFIXES):
            emb += p.numel()
        else:
            non += p.numel()
    return {"embedding": emb, "non_embedding": non, "total": emb + non}


def _fixed(method: str) -> dict[str, Any]:
    return dict(search_space(method).get("fixed") or {})


def nonemb_params(method: str, width: int) -> int:
    """Non-embedding parameter count of ``method`` at ``width`` (independent of vocab size)."""
    m = build_neural(method, vocab_size=16, width=width, dropout=0.1, max_len=8, fixed=_fixed(method))
    return count_params(m)["non_embedding"]


def solve_width(method: str, target: int) -> tuple[int, int]:
    """Width whose non-embedding parameter count is closest to ``target``."""
    best: tuple[int, int] | None = None
    for w in _WIDTH_GRID[method]:
        n = nonemb_params(method, w)
        if best is None or abs(n - target) < abs(best[1] - target):
            best = (w, n)
        if n > 1.3 * target:
            break
    assert best is not None
    return best


def solve_all_widths() -> dict[str, dict[str, int]]:
    """Resolve S/M/L widths for every neural method."""
    targets = global_cfg()["neural"]["width_targets"]
    return {m: {lvl: solve_width(m, int(t))[0] for lvl, t in targets.items()} for m in NEURAL_METHODS}


def write_widths(widths: dict[str, dict[str, int]]) -> None:
    dump_yaml(widths, path("model_widths"))


def model_widths() -> dict[str, dict[str, int]]:
    """Load ``configs/model_widths.yaml``."""
    return load_yaml(path("model_widths"))


def width_for(method: str, level: str) -> int:
    """Concrete width for a level name (``S``/``M``/``L``) or a literal integer."""
    if isinstance(level, int) or str(level).isdigit():
        return int(level)
    return int(model_widths()[method][level])
