"""TF-IDF features shared by the four ML methods (fit on the training subset only).

``kiwi`` / ``whitespace``: the input is a pre-tokenised list; unigrams + bigrams are
generated by sklearn with ``tokenizer=identity, token_pattern=None`` -- the default
``token_pattern`` (``\\w\\w+``) would silently drop 1-character tokens such as 좋/안/못/다.
``char``: ``analyzer="char"`` with 2-4-grams on the normalized string.
All: ``max_features=10000``, L2 norm, ``sublinear_tf=True``, ``min_df=1``, sparse output.
"""
from __future__ import annotations

import numpy as np
from sklearn.feature_extraction.text import TfidfVectorizer

from ksent.config import global_cfg


def identity(x):
    """Identity preprocessing/tokenisation step (module-level so the vectoriser pickles)."""
    return x


def make_vectorizer(tokenizer: str = "kiwi") -> TfidfVectorizer:
    """Build an unfitted vectoriser for ``tokenizer``."""
    c = global_cfg()["tfidf"]
    common = dict(max_features=int(c["max_features"]), sublinear_tf=bool(c["sublinear_tf"]), min_df=c["min_df"],
                  norm=c["norm"], lowercase=False, dtype=np.float64)
    if tokenizer == "char":
        return TfidfVectorizer(analyzer="char", ngram_range=tuple(c["char_ngram_range"]), **common)
    return TfidfVectorizer(tokenizer=identity, preprocessor=identity, token_pattern=None,
                           ngram_range=tuple(c["ngram_range"]), **common)
